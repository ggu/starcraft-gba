/* Cosmetic fog state. Visibility always wins if a stale explored bit remains. */
enum {
    SC64_FOG_UNKNOWN = 0,
    SC64_FOG_EXPLORED = 1,
    SC64_FOG_VISIBLE = 2,
    SC64_FOG_SIGNATURE_COUNT = 19683 /* 3^9 */
};

