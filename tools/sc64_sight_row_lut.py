"""Build ROM-only packed sight spans from integer circle geometry."""

import argparse
from math import isqrt
from pathlib import Path


RADII = tuple(range(64, 177, 16))
MAX_EXTENT = 12
EMPTY = 0xff
SPARSE_STEPS = ((1, 0), (2, 0)) + tuple(
    (dx, dy) for dy in (1, 2) for dx in range(-2, 3)
)


def build_rows():
    for radius in RADII:
        extent = (radius + 23) // 16
        phases = []
        for yp in range(16):
            for xp in range(16):
                rows = []
                for r in range(-MAX_EXTENT, MAX_EXTENT + 1):
                    dy = r * 16 + 8 - yp
                    if abs(r) > extent or abs(dy) > radius:
                        rows.append(EMPTY)
                        continue
                    half = isqrt(radius * radius - dy * dy)
                    first = max(-extent, (xp - half - 8 + 15) // 16)
                    last = min(extent, (xp + half - 8) // 16)
                    if first > last:
                        rows.append(EMPTY)
                    else:
                        assert -15 < first <= 0 <= last < 15
                        rows.append((-first << 4) | last)
                phases.append(rows)
        yield phases


def shifted_interval(rows, col, index):
    if 0 <= index < len(rows) and rows[index] != EMPTY:
        span = rows[index]
        return col - (span >> 4), col + (span & 15)
    return None


def build_sparse_masks():
    for phases in build_rows():
        for dx, dy in SPARSE_STEPS:
            masks = []
            for phase, first_rows in enumerate(phases):
                y, x = divmod(phase, 16)
                col_shift, end_x = divmod(x + dx, 16)
                row_shift, end_y = divmod(y + dy, 16)
                last_rows = phases[end_y * 16 + end_x]
                mask = 0
                for index in range(2 * MAX_EXTENT + 1 + row_shift):
                    if shifted_interval(first_rows, 0, index) != shifted_interval(
                        last_rows, col_shift, index - row_shift
                    ):
                        mask |= 1 << index
                masks.append(mask)
            yield masks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sparse-mask', action='store_true')
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    output = args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', encoding='ascii') as f:
        if args.sparse_mask:
            f.write('/* Sparse sight row masks generated by sc64_sight_row_lut.py. */\n')
            f.write('static const unsigned sc64_z7_sight_sparse_masks[8 * 12][256] = {\n')
            for masks in build_sparse_masks():
                f.write('  {\n')
                for start in range(0, len(masks), 8):
                    f.write('    ' + ','.join(f'0x{v:07x}u' for v in masks[start:start+8]) + ',\n')
                f.write('  },\n')
            f.write('};\n')
            return
        f.write('/* Integer sight spans generated by sc64_sight_row_lut.py. */\n')
        f.write('static const u8 sc64_z7_sight_packed_rows[8][256][25] = {\n')
        for phases in build_rows():
            f.write('  {\n')
            for rows in phases:
                f.write('    {' + ','.join(f'0x{value:02x}' for value in rows) + '},\n')
            f.write('  },\n')
        f.write('};\n')


if __name__ == '__main__':
    main()
