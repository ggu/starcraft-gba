"""Build ROM-only packed sight spans from integer circle geometry."""

import argparse
from math import isqrt
from pathlib import Path


RADII = tuple(range(64, 177, 16))
MAX_EXTENT = 12
EMPTY = 0xff


def build_rows():
    for radius in RADII:
        extent = (radius + 23) // 16
        phases = []
        for yp in range(16):
            for xp in range(16):
                rows = []
                for r in range(-MAX_EXTENT, MAX_EXTENT + 1):
                    dy = r * 16 + 8 - yp
                    if abs(r) > extent or abs(dy) > radius:
                        rows.append(EMPTY)
                        continue
                    half = isqrt(radius * radius - dy * dy)
                    first = max(-extent, (xp - half - 8 + 15) // 16)
                    last = min(extent, (xp + half - 8) // 16)
                    if first > last:
                        rows.append(EMPTY)
                    else:
                        assert -15 < first <= 0 <= last < 15
                        rows.append((-first << 4) | last)
                phases.append(rows)
        yield phases


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    output = parser.parse_args().output
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', encoding='ascii') as f:
        f.write('/* Integer sight spans generated by sc64_sight_row_lut.py. */\n')
        f.write('static const u8 sc64_z7_sight_packed_rows[8][256][25] = {\n')
        for phases in build_rows():
            f.write('  {\n')
            for rows in phases:
                f.write('    {' + ','.join(f'0x{value:02x}' for value in rows) + '},\n')
            f.write('  },\n')
        f.write('};\n')


if __name__ == '__main__':
    main()
