"""Input-only P8/P9 replay from a host controller trace, without a debugger.

`tape TRACE OUT` validates a trace from build/test-sc64-p8-campaign-run and
writes the key-transition header that tests/sc64_p8_arm_replay.c embeds. Tape
tick N is the controller's input call N from the title screen, so the menu,
briefing and pause-menu save are ordinary tape inputs.

`run` starts one isolated mGBA process (its own HOME, config and save
directory; no debugger port) on a replay ROM and keeps its `P8 ` debug lines.
`--sav-in` seeds the save directory first, for the fresh-process resume ROM.

`compare A B` checks two line files (host probe output or ARM logs) for equal
observations at every common tape tick, optionally from `--from-tick` on, and
requires both to end in the same outcome. `--mission 28 --prefix P9` selects
the P9 controller trace, tape macros and probe lines. Emulator evidence only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import pathlib
import pty
import re
import select
import shutil
import subprocess
import sys
import time

TOOLS = pathlib.Path(__file__).resolve().parent
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))

KEY_MASK = 1023
MISSION = 27
PREFIX = "P8"


def sha256(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_trace(path: pathlib.Path) -> dict:
    """Strictly validate a P8 controller trace."""
    transitions: list[tuple[int, int]] = []
    held_before, final, save, meta = 0, None, None, None
    for number, text in enumerate(path.read_text().splitlines(), 1):
        row = json.loads(text)
        kind = row.get("kind")
        if kind == "metadata":
            if meta is not None or row.get("mission") != MISSION:
                raise ValueError(f"trace needs one {PREFIX} metadata record")
            meta = row
        elif kind == "input":
            tick, held, pressed = row.get("call_index"), row.get("held"), row.get("pressed")
            if type(tick) is not int or type(held) is not int or held & ~KEY_MASK:
                raise ValueError(f"line {number}: malformed input")
            if held == held_before or pressed != held & ~held_before:
                raise ValueError(f"line {number}: not a held-key transition")
            if transitions and tick <= transitions[-1][0]:
                raise ValueError(f"line {number}: unordered input tick")
            if tick >= 1 << 22:
                raise ValueError(f"line {number}: tick does not fit the tape")
            transitions.append((tick, held))
            held_before = held
        elif kind == "save":
            if save is not None:
                raise ValueError("trace has more than one save")
            save = row
        elif kind == "checkpoint" and row.get("label") == "final":
            final = row
    if meta is None or final is None:
        raise ValueError("trace needs metadata and a final checkpoint")
    stop = final["call_index"]
    if transitions and transitions[-1][0] >= stop:
        raise ValueError("input at or after the final call")
    if save is not None and not (0 < save["resume_call"] < stop and save["paused"] == 1):
        raise ValueError("save record is not an ordinary pause-menu save")
    return {"transitions": transitions, "stop": stop, "final": final, "save": save,
            "profile": meta.get("profile")}


def write_tape(trace_path: pathlib.Path, out: pathlib.Path) -> dict:
    plan = load_trace(trace_path)
    words = [(tick << 10) | held for tick, held in plan["transitions"]]
    resume = plan["save"]["resume_call"] if plan["save"] else 0
    body = ",\n".join("    " + ",".join(f"0x{w:08x}u" for w in words[i:i + 8])
                      for i in range(0, len(words), 8))
    out.parent.mkdir(parents=True, exist_ok=True)
    p, lower = PREFIX, PREFIX.lower()
    out.write_text(
        f"/* Generated by tools/sc64_p8_arm_replay.py from a {p} controller trace.\n"
        f" * Trace SHA-256 {sha256(trace_path)}. Each word is tick << 10 | held. */\n"
        f"#ifndef SC64_{p}_TAPE_GENERATED_H\n#define SC64_{p}_TAPE_GENERATED_H\n"
        f"#define {p}_TAPE_COUNT {len(words)}u\n"
        f"#define {p}_TAPE_STOP_TICK {plan['stop']}u\n"
        f"#define {p}_TAPE_RESUME_TICK {resume}u\n"
        f"static const u32 {lower}_tape[{max(1, len(words))}] = {{\n{body or '    0'}\n}};\n"
        "#endif\n")
    return plan


def run_mgba(mgba: str, rom: pathlib.Path, out: pathlib.Path, timeout: float,
             sav_in: pathlib.Path | None) -> tuple[str, float]:
    """One isolated mGBA process; returns its P8 debug text and wall time."""
    home, saves = out / "home", out / "saves"
    config = home / ".config" / "mgba"
    config.mkdir(parents=True, exist_ok=True)
    saves.mkdir(parents=True, exist_ok=True)
    if sav_in is not None:
        shutil.copyfile(sav_in, saves / (rom.stem + ".sav"))
    (config / "config.ini").write_text("[ports.qt]\nlogToStdout=1\nlogLevel=7\n")
    env = dict(os.environ, HOME=str(home), XDG_CONFIG_HOME=str(home / ".config"))
    master, slave = pty.openpty()
    began = time.monotonic()
    # Decimal mask 7 = fatal|error|warn: the probe logs at warn; INFO would
    # add every DMA and hours of host I/O per run.
    proc = subprocess.Popen(
        [mgba, "-l", "7", "-C", "mute=1", "-C", "audioSync=0", "-C", "videoSync=0",
         "-C", f"savegamePath={saves}", "-C", f"savestatePath={saves}",
         "-C", f"screenshotPath={out}", str(rom)],
        stdin=subprocess.DEVNULL, stdout=slave, stderr=slave, env=env, cwd=out)
    os.close(slave)
    captured = bytearray()
    log = (out / "mgba.log").open("wb")
    done_at = None
    try:
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline and proc.poll() is None:
            ready, _, _ = select.select([master], [], [], 1.0)
            if ready:
                try:
                    chunk = os.read(master, 65536)
                except OSError:
                    break
                if not chunk:
                    break
                captured.extend(chunk)
                log.write(chunk)
                log.flush()
                if done_at is None and f"{PREFIX} DONE".encode() in captured[-(len(chunk) + 32):]:
                    done_at = time.monotonic()
            # Let mGBA write SRAM back before stopping it.
            if done_at is not None and time.monotonic() - done_at > 5:
                break
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
        os.close(master)
        log.close()
    return captured.decode(errors="replace"), time.monotonic() - began


def p8_lines(text: str) -> list[str]:
    tag = PREFIX + " "
    return [l[l.index(tag):].rstrip() for l in text.splitlines() if tag in l]


def checks(lines: list[str]) -> dict[int, dict]:
    rows = {}
    for line in lines:
        if line.startswith(PREFIX + " CHECK "):
            fields = dict(re.findall(r"(\w+)=(-?\d+)", line))
            fields["kind"] = line.split()[2]
            rows[int(fields["tick"])] = fields
    return rows


def compare(a: list[str], b: list[str], from_tick: int) -> dict:
    ca, cb = checks(a), checks(b)
    common = sorted(t for t in ca if t in cb and t >= from_tick)
    mismatches = []
    for tick in common:
        ra, rb = ca[tick], cb[tick]
        for key in sorted(set(ra) | set(rb)):
            if key != "kind" and ra.get(key) != rb.get(key):
                mismatches.append(f"tick {tick} {key}: {ra.get(key)} != {rb.get(key)}")
    end_a, end_b = (max(c) if c else None for c in (ca, cb))
    return {"compared": len(common), "mismatch_count": len(mismatches),
            "mismatches": mismatches[:40],
            "final_a": ca.get(end_a), "final_b": cb.get(end_b),
            "same_end": end_a == end_b and end_a is not None}


def main() -> None:
    global MISSION, PREFIX
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mission", type=int, choices=(27, 28), default=27)
    parser.add_argument("--prefix", choices=("P8", "P9"), default="P8")
    sub = parser.add_subparsers(dest="command", required=True)
    tape = sub.add_parser("tape", help="write the probe's key-tape header")
    tape.add_argument("trace", type=pathlib.Path)
    tape.add_argument("header", type=pathlib.Path)
    run = sub.add_parser("run", help="replay a ROM in an isolated mGBA process")
    run.add_argument("--rom", type=pathlib.Path, required=True)
    run.add_argument("--out", type=pathlib.Path, required=True)
    run.add_argument("--sav-in", type=pathlib.Path)
    run.add_argument("--timeout", type=float, default=7200)
    cmp = sub.add_parser("compare", help="compare two P8 observation line files")
    cmp.add_argument("a", type=pathlib.Path)
    cmp.add_argument("b", type=pathlib.Path)
    cmp.add_argument("--from-tick", type=int, default=0)
    args = parser.parse_args()
    MISSION, PREFIX = args.mission, args.prefix
    if args.command == "tape":
        plan = write_tape(args.trace, args.header)
        print(json.dumps({"transitions": len(plan["transitions"]), "stop": plan["stop"],
                          "resume": plan["save"]["resume_call"] if plan["save"] else 0,
                          "won": plan["final"]["won"]}))
        return
    if args.command == "compare":
        result = compare(p8_lines(args.a.read_text()), p8_lines(args.b.read_text()),
                         args.from_tick)
        print(json.dumps(result, indent=2))
        ok = result["same_end"] and not result["mismatch_count"] and result["compared"]
        raise SystemExit(0 if ok else 1)
    from emulator_smoke import require_mgba
    out = args.out.resolve()
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"{out} is not empty; choose a fresh --out")
    out.mkdir(parents=True, exist_ok=True)
    text, wall = run_mgba(require_mgba(), args.rom.resolve(), out, args.timeout,
                          args.sav_in.resolve() if args.sav_in else None)
    lines = p8_lines(text)
    (out / "p8-lines.txt").write_text("\n".join(lines) + "\n")
    summary = {"rom": str(args.rom), "rom_sha256": sha256(args.rom),
               "lines": len(lines), "done": any(l.startswith(PREFIX + " DONE") for l in lines),
               "wall_seconds": round(wall, 1),
               "save_files": sorted(p.name for p in (out / "saves").glob("*.sav"))}
    (out / "result.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))
    if not summary["done"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
