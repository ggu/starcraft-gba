#!/usr/bin/env python3
"""Drive tests/sc64_impact_replay.c: tape headers, mGBA runs and comparison.

header  turns a tests/sc64_input_tape_record.h recording into a replay header.
run     launches the diagnostic ROM in fresh mGBA processes (isolated HOME,
        log mask 7, no debugger port). With --phases 2 the second process
        starts from the first one's flushed SRAM, as a cold boot would.
compare checks that every ARM world line matches the host oracle's line with
        the same tag and tick, and that a load phase repeats the save phase.

Emulator cycle counts are not hardware results.
"""
# SPDX-License-Identifier: GPL-3.0-or-later
from __future__ import annotations

import argparse
import hashlib
import json
import os
import pathlib
import re
import shutil

from emulator_smoke import ROOT, require_mgba
from sc64_impact_arm_probe import run as run_mgba

WORLD_TAGS = ("LAUNCH", "SNAP", "TERMINAL", "SAVED", "RESTORED", "CONT")


def header(record: pathlib.Path, out: pathlib.Path) -> None:
    rows, end = [], None
    for text in record.read_text().splitlines():
        parts = text.split()
        if parts[0] == "end":
            end = int(parts[1])
            continue
        tick, held = int(parts[0]), int(parts[1])
        if rows and tick <= rows[-1][0]:
            raise SystemExit(f"{record}: ticks must increase")
        if not 0 <= held <= 0x3ff:
            raise SystemExit(f"{record}: held keys out of range at tick {tick}")
        rows.append((tick, held))
    if end is None or (rows and rows[-1][0] > end):
        raise SystemExit(f"{record}: missing or short end marker")
    digest = hashlib.sha256(record.read_bytes()).hexdigest()
    body = ",\n".join(f"    {{{t}u,{h}u}}" for t, h in rows)
    out.write_text(
        "/* Generated by tools/sc64_impact_replay.py header; held-key changes only. */\n"
        f"/* Recording SHA-256 {digest} */\n"
        "typedef struct { u32 tick; u16 held; } Sc64TapeInput;\n"
        f"static const Sc64TapeInput sc64_tape[] = {{\n{body}\n}};\n"
        f"#define SC64_TAPE_COUNT {len(rows)}u\n#define SC64_TAPE_TICKS {end}u\n")
    print(f"{out}: {len(rows)} transitions, {end} ticks, recording {digest[:16]}")


def parse(lines: list[str]) -> list[dict[str, str]]:
    rows = []
    for text in lines:
        tag = text.split()[1]
        rows.append({"tag": tag, **dict(re.findall(r"(\w+)=(\S+)", text))})
    return rows


def run(rom: pathlib.Path, out: pathlib.Path, phases: int, timeout: float) -> None:
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"{out} is not empty; choose a fresh --out")
    mgba = require_mgba()
    summary = {"rom": str(rom), "rom_sha256": hashlib.sha256(rom.read_bytes()).hexdigest(),
               "phases": []}
    for phase in range(phases):
        directory = out / f"phase{phase + 1}"
        directory.mkdir(parents=True)
        if phase:
            shutil.copytree(out / f"phase{phase}" / "saves", directory / "saves")
        lines = run_mgba(mgba, rom, directory, timeout)
        saves = sorted((directory / "saves").glob("*.sav"))
        summary["phases"].append({
            "lines": lines,
            "sram_sha256": [hashlib.sha256(p.read_bytes()).hexdigest() for p in saves],
            "done": "IMPACT DONE" in lines})
        (directory / "lines.txt").write_text("\n".join(lines) + "\n")
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    for i, phase in enumerate(summary["phases"], 1):
        result = next((r for r in parse(phase["lines"]) if r["tag"] == "RESULT"), {})
        print(f"phase{i}: done={phase['done']} result={result} sram={phase['sram_sha256']}")
    if not all(p["done"] for p in summary["phases"]):
        raise SystemExit(1)


def world(rows: list[dict[str, str]]) -> dict[tuple[str, str], dict[str, str]]:
    return {(r["tag"], r["tick"]): r for r in rows if r["tag"] in WORLD_TAGS}


def compare(host: pathlib.Path, arm: list[pathlib.Path]) -> None:
    host_rows = parse([t for t in host.read_text().splitlines() if t.startswith("IMPACT ")])
    # The host oracle prints one DONE per phase; split it the same way.
    host_phases, current = [], []
    for row in host_rows:
        current.append(row)
        if row["tag"] == "DONE":
            host_phases.append(current)
            current = []
    if len(host_phases) != len(arm):
        raise SystemExit(f"host has {len(host_phases)} phases, ARM has {len(arm)}")
    failures, checked = [], 0
    arm_worlds = []
    for index, (expected, path) in enumerate(zip(host_phases, arm), 1):
        got = world(parse(path.read_text().splitlines()))
        want = world(expected)
        arm_worlds.append(got)
        if set(got) != set(want):
            failures.append(f"phase{index}: checkpoint sets differ "
                            f"(missing {sorted(set(want) - set(got))[:4]}, "
                            f"extra {sorted(set(got) - set(want))[:4]})")
        for key in sorted(set(got) & set(want)):
            checked += 1
            for field in ("frame", "won", "lost", "pending", "digest"):
                if got[key].get(field) != want[key].get(field):
                    failures.append(f"phase{index} {key}: {field} {got[key].get(field)} "
                                    f"!= host {want[key].get(field)}")
    if len(arm_worlds) == 2:
        saved = next((r for k, r in arm_worlds[0].items() if k[0] == "SAVED"), None)
        restored = next((r for k, r in arm_worlds[1].items() if k[0] == "RESTORED"), None)
        if not saved or not restored or saved["digest"] != restored["digest"] \
                or saved["frame"] != restored["frame"] or saved["pending"] != restored["pending"]:
            failures.append(f"restored world differs from saved world: {saved} vs {restored}")
        first = {k[1]: r for k, r in arm_worlds[0].items() if k[0] == "CONT"}
        second = {k[1]: r for k, r in arm_worlds[1].items() if k[0] == "CONT"}
        if not first or first.keys() != second.keys():
            failures.append("continuation checkpoint sets differ between processes")
        for tick in sorted(set(first) & set(second), key=int):
            checked += 1
            if first[tick]["digest"] != second[tick]["digest"]:
                failures.append(f"continuation d={tick} differs between processes")
    print(f"compared {checked} checkpoints; {len(failures)} failures")
    for failure in failures[:20]:
        print("  " + failure)
    if failures:
        raise SystemExit(1)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    h = sub.add_parser("header")
    h.add_argument("record", type=pathlib.Path)
    h.add_argument("out", type=pathlib.Path)
    r = sub.add_parser("run")
    r.add_argument("rom", type=pathlib.Path)
    r.add_argument("--out", type=pathlib.Path, required=True)
    r.add_argument("--phases", type=int, choices=(1, 2), default=1)
    r.add_argument("--timeout", type=float, default=3600)
    c = sub.add_parser("compare")
    c.add_argument("host", type=pathlib.Path)
    c.add_argument("arm", type=pathlib.Path, nargs="+")
    args = parser.parse_args()
    if args.command == "header":
        header(args.record, args.out)
    elif args.command == "run":
        run(args.rom.resolve(), args.out.resolve(), args.phases, args.timeout)
    else:
        compare(args.host, args.arm)


if __name__ == "__main__":
    os.chdir(ROOT)
    main()
