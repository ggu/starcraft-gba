"""Render a private Z9 or Z10 descriptor as the ROM tables its runtime embeds.

The input is an authenticated descriptor written by
``sc64_zerg_late_pack.py pack`` (and checked by its ``validate_structure``).
The output is a private generated C header under an ignored build path,
holding the scheduler-layout trigger, condition, action and location rows,
the mission-start owner and force setup and the PUNI permission bitmap. Row
layouts are the Z8 scheduler's. It contains extracted game data: do not
commit or distribute it.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))

import sc64_z8_pack  # noqa: E402
import sc64_z8_program_pack as z8p  # noqa: E402
import sc64_zerg_late_pack as late  # noqa: E402


def render(descriptor: dict) -> str:
    late.require_authenticated(descriptor)
    mission = descriptor['mission']
    lower, upper = mission.lower(), mission.upper()
    prefix, macro = f'sc64_{lower}_program', f'SC64_{upper}_PROGRAM'
    permissions = z8p.permission_bitmap(descriptor['puni'])
    permission_rows = ',\n'.join(
        '    ' + ','.join(f'{v}u' for v in permissions[i:i + 24])
        for i in range(0, len(permissions), 24))
    active, forces = z8p.setup(descriptor)
    width = descriptor['dimensions']['width'] * 32
    height = descriptor['dimensions']['height'] * 32
    triggers = ',\n'.join(
        '    {' + ','.join(f'{int(t[f])}u' for f in z8p.TRIGGER_FIELDS) +
        ',{' + ','.join(f'{int(v)}u' for v in t['enabled_players']) + '}}'
        for t in descriptor['triggers'])
    return f"""/* Private generated data. Do not commit or distribute. */
/* Generated by tools/sc64_zerg_late_program_pack.py from the authenticated
 * {mission} descriptor {descriptor['descriptor_sha256']}. */
#ifndef SC64_{upper}_PROGRAM_GENERATED_H
#define SC64_{upper}_PROGRAM_GENERATED_H
#include "sc64_z8_permissions.h"
#define {macro}_DESCRIPTOR_SHA256 "{descriptor['descriptor_sha256']}"
#define {macro}_TRIGGER_COUNT {len(descriptor['triggers'])}u
#define {macro}_CONDITION_COUNT {len(descriptor['conditions'])}u
#define {macro}_ACTION_COUNT {len(descriptor['actions'])}u
#define {macro}_LOCATION_COUNT {len(descriptor['locations'])}u
#define {macro}_MAP_PIXEL_WIDTH {width}u
#define {macro}_MAP_PIXEL_HEIGHT {height}u
#define {macro}_ACTIVE_MASK {active}u
static const Sc64Z8PermissionTable {prefix}_permissions = {{{{
{permission_rows}
}}}};
static const u8 {prefix}_forces[8] = {{{','.join(f'{f}u' for f in forces)}}};
static const Sc64Z8Trigger {prefix}_triggers[{len(descriptor['triggers'])}] = {{
{triggers}
}};
static const Sc64Z8Condition {prefix}_conditions[{len(descriptor['conditions'])}] = {{
{z8p._rows(descriptor['conditions'], z8p.CONDITION_FIELDS)}
}};
static const Sc64Z8Action {prefix}_actions[{len(descriptor['actions'])}] = {{
{z8p._rows(descriptor['actions'], z8p.ACTION_FIELDS)}
}};
static const Sc64Z8SourceLocation {prefix}_locations[{len(descriptor['locations'])}] = {{
{z8p._rows(descriptor['locations'], z8p.LOCATION_FIELDS)}
}};
#endif
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('descriptor', type=Path)
    parser.add_argument('out', type=Path)
    args = parser.parse_args(argv)
    descriptor = json.loads(args.descriptor.read_text(encoding='utf-8'),
                            object_pairs_hook=sc64_z8_pack._unique_json_object)
    text = render(descriptor)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.out.with_suffix('.tmp')
    tmp.write_text(text, encoding='ascii')
    tmp.replace(args.out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
