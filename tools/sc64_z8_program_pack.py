"""Render the private Z8 descriptor as the ROM tables the Z8 runtime embeds.

The input is the authenticated descriptor written by ``sc64_z8_pack.py pack``
(and checked by its ``validate_structure``). The output is a private generated
C header under an ignored build path. It holds the scheduler-layout trigger,
condition, action and location rows, the mission-start owner and force setup,
and the four linked Nydus Canal records at their runtime spawn centres
(engine pixels are source pixels / 2). It contains extracted game data: do
not commit or distribute it.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))

import sc64_z8_pack

TRIGGER_FIELDS = ('first_condition', 'condition_count', 'first_action',
                  'action_count', 'execution_flags', 'initial_cursor')
CONDITION_FIELDS = ('location', 'player', 'amount', 'unit', 'mask', 'comparison',
                    'opcode', 'resource', 'flags', 'index')
ACTION_FIELDS = ('location', 'string_id', 'wav_id', 'time', 'group1', 'group2',
                 'unit', 'opcode', 'modifier', 'flags', 'index')
LOCATION_FIELDS = ('left', 'top', 'right', 'bottom', 'flags')
NYDUS_RAW = 134
OWNER_COMPUTER, OWNER_HUMAN = 5, 6
PUNI_OWNERS, PUNI_UNITS = 12, 228
PUNI_CELLS = PUNI_OWNERS * PUNI_UNITS
PUNI_LENGTH = PUNI_CELLS * 2 + PUNI_UNITS
PERMISSION_BYTES = (PUNI_CELLS + 7) // 8


def _rows(rows: list[dict], fields: tuple[str, ...]) -> str:
    return ',\n'.join('    {' + ','.join(f'{int(row[f])}u' for f in fields) + '}'
                      for row in rows)


def setup(descriptor: dict) -> tuple[int, list[int]]:
    """Active-owner mask (OWNR computer or human) and one-based FORC forces."""
    owners, forces = descriptor['owners'], descriptor['forces']
    active = sum(1 << slot for slot in range(8) if owners[slot] in (OWNER_COMPUTER, OWNER_HUMAN))
    return active, [forces[slot] + 1 for slot in range(8)]


def nydus_records(descriptor: dict) -> list[dict]:
    rows = [r for r in descriptor['unit_records'] if r['source_type'] == NYDUS_RAW]
    by_index = {r['record_index']: r for r in rows}
    for row in rows:
        partner = by_index.get(row['linked_record_index'])
        if partner is None or partner['linked_record_index'] != row['record_index']:
            raise ValueError(f"Nydus record {row['record_index']} has no reciprocal link")
        if row['x_source_px'] % 2 or row['y_source_px'] % 2:
            raise ValueError(f"Nydus record {row['record_index']} is not on an engine pixel")
    pairs = sorted(sorted((r['record_index'], r['linked_record_index'])) for r in rows)
    if [list(p) for p in pairs[::2]] != descriptor['nydus_pairs']:
        raise ValueError('Nydus records disagree with the descriptor pair list')
    return sorted(rows, key=lambda r: r['record_index'])


def permission_bitmap(puni: list[int]) -> bytes:
    """Resolve PUNI player overrides/defaults into a bounded source-slot bitmap."""
    if not isinstance(puni, list) or len(puni) != PUNI_LENGTH:
        raise ValueError('PUNI must contain exactly 5700 boolean cells')
    if any(type(v) is not int or v not in (0, 1) for v in puni):
        raise ValueError('PUNI cells must be integer zero or one')
    result = bytearray(PERMISSION_BYTES)
    for owner in range(PUNI_OWNERS):
        for raw in range(PUNI_UNITS):
            index = owner * PUNI_UNITS + raw
            use_global = puni[PUNI_CELLS + PUNI_UNITS + index]
            allowed = puni[PUNI_CELLS + raw] if use_global else puni[index]
            if allowed:
                result[index // 8] |= 1 << (index % 8)
    return bytes(result)


def render(descriptor: dict) -> str:
    sc64_z8_pack.validate_structure(descriptor)
    if descriptor.get('descriptor_sha256') != sc64_z8_pack.EXPECTED_DESCRIPTOR_SHA256:
        raise ValueError('descriptor fingerprint is not the authenticated Z8 source')
    permissions = permission_bitmap(descriptor['puni'])
    permission_rows = ',\n'.join(
        '    ' + ','.join(f'{v}u' for v in permissions[i:i + 24])
        for i in range(0, len(permissions), 24))
    active, forces = setup(descriptor)
    width = descriptor['dimensions']['width'] * 32
    height = descriptor['dimensions']['height'] * 32
    triggers = ',\n'.join(
        '    {' + ','.join(f'{int(t[f])}u' for f in TRIGGER_FIELDS) +
        ',{' + ','.join(f'{int(v)}u' for v in t['enabled_players']) + '}}'
        for t in descriptor['triggers'])
    nydus = nydus_records(descriptor)
    nydus_rows = ',\n'.join(
        f"    {{{r['record_index']}u,{r['linked_record_index']}u,{NYDUS_RAW}u,{r['relation']}u,"
        f"{r['owner_raw']}u,0u,{r['x_source_px'] // 2},{r['y_source_px'] // 2}}}"
        for r in nydus)
    return f"""/* Private generated data. Do not commit or distribute. */
/* Generated by tools/sc64_z8_program_pack.py from the authenticated Z8
 * descriptor {descriptor['descriptor_sha256']}. */
#ifndef SC64_Z8_PROGRAM_GENERATED_H
#define SC64_Z8_PROGRAM_GENERATED_H
#include "sc64_z8_permissions.h"
#define SC64_Z8_PROGRAM_DESCRIPTOR_SHA256 "{descriptor['descriptor_sha256']}"
#define SC64_Z8_PROGRAM_TRIGGER_COUNT {len(descriptor['triggers'])}u
#define SC64_Z8_PROGRAM_CONDITION_COUNT {len(descriptor['conditions'])}u
#define SC64_Z8_PROGRAM_ACTION_COUNT {len(descriptor['actions'])}u
#define SC64_Z8_PROGRAM_LOCATION_COUNT {len(descriptor['locations'])}u
#define SC64_Z8_PROGRAM_MAP_PIXEL_WIDTH {width}u
#define SC64_Z8_PROGRAM_MAP_PIXEL_HEIGHT {height}u
#define SC64_Z8_PROGRAM_ACTIVE_MASK {active}u
#define SC64_Z8_PROGRAM_NYDUS_COUNT {len(nydus)}u
static const Sc64Z8PermissionTable sc64_z8_permission_table = {{{{
{permission_rows}
}}}};
static const u8 sc64_z8_program_forces[8] = {{{','.join(f'{f}u' for f in forces)}}};
static const Sc64Z8Trigger sc64_z8_program_triggers[{len(descriptor['triggers'])}] = {{
{triggers}
}};
static const Sc64Z8Condition sc64_z8_program_conditions[{len(descriptor['conditions'])}] = {{
{_rows(descriptor['conditions'], CONDITION_FIELDS)}
}};
static const Sc64Z8Action sc64_z8_program_actions[{len(descriptor['actions'])}] = {{
{_rows(descriptor['actions'], ACTION_FIELDS)}
}};
static const Sc64Z8SourceLocation sc64_z8_program_locations[{len(descriptor['locations'])}] = {{
{_rows(descriptor['locations'], LOCATION_FIELDS)}
}};
static const Sc64NydusSourceRecord sc64_z8_program_nydus[{len(nydus)}] = {{
{nydus_rows}
}};
#endif
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('descriptor', type=Path)
    parser.add_argument('out', type=Path)
    args = parser.parse_args(argv)
    descriptor = json.loads(args.descriptor.read_text(encoding='utf-8'),
                            object_pairs_hook=sc64_z8_pack._unique_json_object)
    text = render(descriptor)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.out.with_suffix('.tmp')
    tmp.write_text(text, encoding='ascii')
    tmp.replace(args.out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
