"""Generate the authored, ROM-resident contact-mask geometry lookup.

The output is a build artifact, not imported game data.  It encodes only the
integer circle/strict-boundary predicate used by sc64_contact.h.
"""
from __future__ import annotations

import argparse
from pathlib import Path

RADIUS_MIN = 6
RADIUS_MAX = 19
SPEED_MIN = 0
SPEED_MAX = 14
OFFSET_MIN = -32
OFFSET_MAX = 32
DX = (1, 1, 0, -1, -1, -1, 0, 1)
DY = (0, 1, 1, 1, 0, -1, -1, -1)


def blocked_mask(radius: int, speed: int, ox: int, oy: int) -> int:
    mask = 0
    origin_distance = ox * ox + oy * oy
    for direction in range(8):
        dx = ox - DX[direction] * speed
        dy = oy - DY[direction] * speed
        if dx <= -radius or dx >= radius or dy <= -radius or dy >= radius:
            continue
        distance = dx * dx + dy * dy
        if distance < radius * radius and distance <= origin_distance:
            mask |= 1 << direction
    return mask


def generate(path: Path) -> int:
    values = bytearray()
    for radius in range(RADIUS_MIN, RADIUS_MAX + 1):
        for speed in range(SPEED_MIN, SPEED_MAX + 1):
            for oy in range(OFFSET_MIN, OFFSET_MAX + 1):
                for ox in range(OFFSET_MIN, OFFSET_MAX + 1):
                    values.append(blocked_mask(radius, speed, ox, oy))
    expected = (RADIUS_MAX - RADIUS_MIN + 1) * (SPEED_MAX - SPEED_MIN + 1) * 65 * 65
    assert len(values) == expected
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="ascii", newline="\n") as out:
        out.write("/* Generated by tools/sc64_contact_mask_table_gen.py; authored integer geometry only. */\n")
        out.write(f"#define SC64_CONTACT_MASK_TABLE_RADIUS_MIN {RADIUS_MIN}u\n")
        out.write(f"#define SC64_CONTACT_MASK_TABLE_RADIUS_COUNT {RADIUS_MAX - RADIUS_MIN + 1}u\n")
        out.write(f"#define SC64_CONTACT_MASK_TABLE_SPEED_COUNT {SPEED_MAX - SPEED_MIN + 1}u\n")
        out.write("#define SC64_CONTACT_MASK_TABLE_SIDE 65u\n")
        out.write(f"static const u8 sc64_contact_mask_table_data[{len(values)}u] = {{\n")
        for start in range(0, len(values), 16):
            row = values[start : start + 16]
            out.write("    " + ", ".join(f"0x{x:02x}u" for x in row) + ",\n")
        out.write("};\n")
    return len(values)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True, help="ignored build-directory header output")
    args = parser.parse_args()
    print(f"generated {generate(args.out)} bytes of contact geometry table: {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
